"""Opening names, from the lichess-org/chess-openings dataset (CC0).

`app/data/openings.json` maps a position key to its ECO code and name; it is
generated by `scripts/build_openings.py`.
"""
from __future__ import annotations

import json
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

import chess

DATA_FILE = Path(__file__).resolve().parents[1] / "data" / "openings.json"


@dataclass(frozen=True)
class Opening:
    eco: str
    name: str
    ply: int
    line: str

    @property
    def family(self) -> str:
        """"Sicilian Defense: Najdorf Variation" -> "Sicilian Defense"."""
        return self.name.split(":")[0].strip()


@lru_cache(maxsize=1)
def _table() -> dict[str, Opening]:
    raw = json.loads(DATA_FILE.read_text(encoding="utf-8"))
    return {key: Opening(*value) for key, value in raw.items()}


def lookup(key: str) -> Opening | None:
    """Opening named exactly at this position, if any."""
    return _table().get(key)


def classify(keys: list[str]) -> Opening | None:
    """Deepest named position among the positions a game went through."""
    table = _table()
    for key in reversed(keys):
        opening = table.get(key)
        if opening is not None:
            return opening
    return None


def classify_line(sans: list[str]) -> Opening | None:
    """Deepest named position along a line of SAN moves from the start."""
    board = chess.Board()
    keys: list[str] = []
    for san in sans:
        try:
            board.push_san(san)
        except ValueError:
            break
        keys.append(board.epd())
    return classify(keys)


def line_of(name: str) -> str:
    """Moves leading to the position an opening is named at."""
    return _lines_by_name().get(name, "")


@lru_cache(maxsize=1)
def _lines_by_name() -> dict[str, str]:
    return {opening.name: opening.line for opening in _table().values()}
